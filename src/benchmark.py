"""Reproduce the reference run and put a floor and a ceiling around it.

    python -m src.benchmark

The reference run reported five scores between 0.759 and 0.826 accuracy with
nothing to read them against. Two reference points are missing, and both are
computable rather than arguable.

The floor is what predicting the larger class alone achieves, which on a 60/40
split is 0.60. The ceiling is what a classifier that knew the generative process
exactly would achieve, which `src/ceiling.py` computes to be about 0.857. Every
model here lands between those, and the interesting quantity is the share of the
distance it covers.

Selection happens on cross-validation over the training split. The test split is
scored once per model and never chooses anything. That was already true of the
reference run and is kept.

Writes results/benchmark.json.
"""

from __future__ import annotations

import argparse
import json
import platform
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

from .models import FEATURE_COLUMNS, SEED, TARGET, XGBOOST_GRID, build_models

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "benchmark.json"
DATA = ROOT / "data" / "water_quality.csv"

TEST_FRACTION = 0.2
FOLDS = 5


def load_frame(samples: int = 5000, seed: int = SEED) -> pd.DataFrame:
    """The generated dataset, rebuilt if it is not on disk."""
    if DATA.is_file():
        return pd.read_csv(DATA)
    from .generate_data import generate_water_data
    frame = generate_water_data(n_samples=samples, seed=seed)
    DATA.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(DATA, index=False)
    return frame


def describe_data(frame: pd.DataFrame) -> dict:
    """Row counts, class balance, missingness and duplicates, all measured."""
    counts = frame[TARGET].value_counts().to_dict()
    duplicated_features = int(frame[FEATURE_COLUMNS].duplicated().sum())
    return {
        "rows": len(frame),
        "features": len(FEATURE_COLUMNS),
        "feature_names": list(FEATURE_COLUMNS),
        "target": TARGET,
        "class_counts": {str(k): int(v) for k, v in sorted(counts.items())},
        "positive_rate": round(float(frame[TARGET].mean()), 5),
        "majority_class_share": round(
            float(max(frame[TARGET].mean(), 1 - frame[TARGET].mean())), 5),
        "missing_per_feature": {
            name: int(frame[name].isna().sum()) for name in FEATURE_COLUMNS},
        "missing_share_per_feature": {
            name: round(float(frame[name].isna().mean()), 5)
            for name in FEATURE_COLUMNS},
        "rows_with_any_missing": int(frame[FEATURE_COLUMNS].isna().any(axis=1).sum()),
        "duplicate_feature_rows": duplicated_features,
        "source": "generated by src/generate_data.py; no measurement, no external "
                  "dataset, no laboratory record",
    }


def score(actual, predicted, probability=None) -> dict:
    """Metrics that survive a 60/40 split, not accuracy alone."""
    from sklearn.metrics import (
        accuracy_score,
        average_precision_score,
        balanced_accuracy_score,
        confusion_matrix,
        f1_score,
        precision_score,
        recall_score,
        roc_auc_score,
    )

    result = {
        "accuracy": float(accuracy_score(actual, predicted)),
        "balanced_accuracy": float(balanced_accuracy_score(actual, predicted)),
        "precision": float(precision_score(actual, predicted, zero_division=0)),
        "recall": float(recall_score(actual, predicted, zero_division=0)),
        "f1": float(f1_score(actual, predicted, zero_division=0)),
        "confusion_matrix": confusion_matrix(actual, predicted).tolist(),
        "n": len(actual),
    }
    if probability is not None:
        result["roc_auc"] = float(roc_auc_score(actual, probability))
        result["pr_auc"] = float(average_precision_score(actual, probability))
    return result


def bayes_oracle(frame_test) -> tuple:
    """The optimal rule, applied to this particular test split.

    Not a model and not trained on anything. It reads the generator's parameters
    and applies them, so it marks where the data stops being separable rather
    than where a method stops working.
    """
    from .ceiling import bayes_log_odds
    log_odds = bayes_log_odds(frame_test)
    return (log_odds > 0).astype(int), log_odds


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUT)
    arguments = parser.parse_args()

    from sklearn.model_selection import (
        GridSearchCV,
        StratifiedKFold,
        cross_val_score,
        train_test_split,
    )

    frame = load_frame()
    data = describe_data(frame)
    print(f"  {data['rows']:,} generated rows, {data['features']} features")
    print(f"  class balance {data['class_counts']}, "
          f"majority share {data['majority_class_share'] * 100:.2f} percent")
    print(f"  rows with a missing value: {data['rows_with_any_missing']:,}")

    features = frame[FEATURE_COLUMNS]
    target = frame[TARGET]
    index_train, index_test = train_test_split(
        np.arange(len(frame)), test_size=TEST_FRACTION, random_state=SEED,
        stratify=target)
    x_train, x_test = features.iloc[index_train], features.iloc[index_test]
    y_train, y_test = target.iloc[index_train], target.iloc[index_test]
    print(f"  train {len(x_train):,}   test {len(x_test):,}, stratified, seed {SEED}\n")

    folds = StratifiedKFold(n_splits=FOLDS, shuffle=True, random_state=SEED)
    results = {}

    # The floor. Any accuracy has to be read against this before anything else.
    majority = int(y_train.value_counts().idxmax())
    results["majority_class"] = {
        "label": f"always predict class {majority}",
        "test": score(y_test, np.full(len(y_test), majority)),
        "cv_f1_mean": 0.0,
        "fit_seconds": 0.0,
        "tuned": False,
    }

    for name, model in build_models().items():
        started = time.perf_counter()
        cv = cross_val_score(model, x_train, y_train, cv=folds, scoring="f1")
        model.fit(x_train, y_train)
        seconds = time.perf_counter() - started
        probability = model.predict_proba(x_test)[:, 1]
        results[name] = {
            "label": name,
            "test": score(y_test, model.predict(x_test), probability),
            "cv_f1_mean": round(float(cv.mean()), 5),
            "cv_f1_std": round(float(cv.std()), 5),
            "fit_seconds": round(seconds, 2),
            "tuned": False,
            "predictions": {"predicted": model.predict(x_test).tolist(),
                            "probability": [round(float(p), 6) for p in probability]},
        }
        print(f"  {name:<22} cv F1 {cv.mean():.4f}   test acc "
              f"{results[name]['test']['accuracy']:.4f}   "
              f"F1 {results[name]['test']['f1']:.4f}")

    # Only XGBoost is tuned, exactly as the reference run did it. The comparison
    # is therefore between one searched model and three unsearched ones.
    started = time.perf_counter()
    search = GridSearchCV(build_models()["XGBoost"], XGBOOST_GRID, cv=FOLDS,
                          scoring="f1", n_jobs=-1)
    search.fit(x_train, y_train)
    seconds = time.perf_counter() - started
    tuned_probability = search.best_estimator_.predict_proba(x_test)[:, 1]
    results["XGBoost (Tuned)"] = {
        "label": "XGBoost, grid searched",
        "test": score(y_test, search.predict(x_test), tuned_probability),
        "cv_f1_mean": round(float(search.best_score_), 5),
        "best_params": {k: (v.item() if hasattr(v, "item") else v)
                        for k, v in search.best_params_.items()},
        "grid_searched": XGBOOST_GRID,
        "chosen_at_grid_edge": [
            key for key, value in search.best_params_.items()
            if value in (min(XGBOOST_GRID[key]), max(XGBOOST_GRID[key]))],
        "fit_seconds": round(seconds, 2),
        "tuned": True,
        "predictions": {"predicted": search.predict(x_test).tolist(),
                        "probability": [round(float(p), 6)
                                        for p in tuned_probability]},
    }
    print(f"  {'XGBoost (Tuned)':<22} cv F1 {search.best_score_:.4f}   test acc "
          f"{results['XGBoost (Tuned)']['test']['accuracy']:.4f}")

    # The ceiling, applied to this same test split.
    predicted, log_odds = bayes_oracle(frame.iloc[index_test])
    results["bayes_optimal"] = {
        "label": "the generator's own rule, not a trained model",
        "test": score(y_test, predicted, log_odds),
        "cv_f1_mean": None,
        "fit_seconds": 0.0,
        "tuned": False,
    }

    # Selection on cross-validation, stated rather than implied.
    trained = {k: v for k, v in results.items()
               if v.get("cv_f1_mean") not in (None, 0.0)}
    chosen = max(trained, key=lambda k: trained[k]["cv_f1_mean"])

    floor = results["majority_class"]["test"]["accuracy"]
    roof = results["bayes_optimal"]["test"]["accuracy"]
    for entry in results.values():
        span = roof - floor
        entry["share_of_available_signal"] = (
            round((entry["test"]["accuracy"] - floor) / span, 4) if span else None)

    print(f"\n  floor {floor * 100:.2f} (majority class), "
          f"ceiling {roof * 100:.2f} (the generator's own rule)")
    print(f"  cross-validation selects {chosen}")
    print(f"\n  {'model':<22} {'test acc':>9} {'bal acc':>9} {'F1':>8} "
          f"{'ROC-AUC':>9} {'of available':>13}")
    for name, entry in sorted(results.items(),
                              key=lambda kv: kv[1]["test"]["accuracy"]):
        test = entry["test"]
        share = entry["share_of_available_signal"]
        print(f"  {name:<22} {test['accuracy'] * 100:9.2f} "
              f"{test['balanced_accuracy'] * 100:9.2f} {test['f1'] * 100:8.2f} "
              f"{test.get('roc_auc', float('nan')):9.4f} "
              f"{'' if share is None else f'{share * 100:12.1f}%'}")

    payload = {}
    if arguments.out.exists():
        payload = json.loads(arguments.out.read_text(encoding="utf-8"))
    payload["environment"] = {
        "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "python": platform.python_version(),
    }
    payload["data"] = data
    payload["split"] = {
        "test_fraction": TEST_FRACTION, "stratified": True, "seed": SEED,
        "train_rows": len(x_train), "test_rows": len(x_test),
        "folds": FOLDS,
        "note": "imputer and scaler live inside each Pipeline, so both are fitted "
                "on the training fold only and never see the data they are scored "
                "against",
    }
    payload["models"] = results
    payload["selection"] = {
        "criterion": f"mean F1 over {FOLDS}-fold stratified cross-validation on the "
                     f"training split",
        "chosen": chosen,
        "note": "the test split was scored once per model and selected nothing",
    }
    payload["reference_points"] = {
        "floor_accuracy": floor,
        "ceiling_accuracy": roof,
        "available_span": round(roof - floor, 5),
    }

    arguments.out.parent.mkdir(parents=True, exist_ok=True)
    arguments.out.write_text(json.dumps(payload, indent=2) + "\n",
                             encoding="utf-8", newline="\n")
    print(f"\n  wrote {arguments.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
